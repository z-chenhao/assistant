import {assertDeveloperList} from './channels_controls.mjs';
import {writeFile} from 'node:fs/promises';
// The trace list and peek panel use the actual Web query and read model.
export async function traceList(page,context,browser,url,evidence,facts){
 const setViewport=async viewport=>{await page.setViewportSize(viewport);await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))};
 const list=url+'/developer/observability';
 const assertRows=async(expected)=>{await page.waitForFunction(count=>document.querySelectorAll('[data-execution-id]').length===count,expected)};
 await page.getByRole('searchbox',{name:'Search traces',exact:true}).fill(facts.main);
 await page.getByRole('searchbox',{name:'Search traces',exact:true}).press('Enter');
 await page.waitForURL(target=>target.searchParams.get('search')===facts.main);await assertRows(1);
 await page.getByRole('radio',{name:'Root Worker',exact:true}).check();
 await page.getByRole('button',{name:'Apply filters',exact:true}).click();
 await page.getByRole('heading',{name:'No matching traces',exact:true}).waitFor();
 await page.getByRole('link',{name:'Clear all',exact:true}).first().click();
 await page.getByRole('button',{name:'All time',exact:true}).click();
 const panel=page.getByRole('dialog',{name:'All time',exact:true});await panel.waitFor();
 await page.getByLabel('Created before (UTC)').fill('2000-01-01T00:00');
 await page.getByRole('button',{name:'Apply range',exact:true}).click();
 await page.getByRole('heading',{name:'No matching traces',exact:true}).waitFor();
 await page.getByRole('link',{name:'Clear all',exact:true}).first().click();
 await page.getByRole('button',{name:'All time',exact:true}).click();
 await page.getByRole('link',{name:'Last 7 days',exact:true}).click();
 await page.waitForURL(target=>target.searchParams.has('since'));
 await page.getByRole('button',{name:'Custom range',exact:true}).click();
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Custom range',exact:true}).and(page.locator(':focus')).waitFor();
 await page.goto(list);
 await page.getByRole('button',{name:'Columns',exact:true}).click();
 await page.getByRole('checkbox',{name:'Show column: Input',exact:true}).uncheck();
 await page.keyboard.press('Escape');await page.reload();
 await page.getByRole('columnheader',{name:'Input',exact:true}).waitFor({state:'hidden'});
 await page.getByRole('button',{name:'Columns',exact:true}).click();
 await page.getByRole('checkbox',{name:'Show column: Input',exact:true}).check();
 await page.keyboard.press('Escape');
 const density=await page.locator('.obs-trace-list tbody tr').first().evaluate(row=>({height:row.getBoundingClientRect().height,font:parseFloat(getComputedStyle(row.querySelector('td')).fontSize)}));
 if(density.height>38||density.font!==12)throw Error('trace rows left the compact density: '+JSON.stringify(density));
 if(!await page.locator('.workspace-topbar').getByRole('button',{name:'All time',exact:true}).isVisible())throw Error('time range left the global header');
 await assertDeveloperList(page);
 const total=(await (await context.request.get(url+'/api/developer/traces')).json()).total;
 const activity=await page.locator('[data-trace-activity]').evaluate(node=>JSON.parse(node.dataset.traceActivity));
 if(activity.reduce((sum,bucket)=>sum+bucket.count,0)!==total)throw Error('activity histogram is not the complete filtered trace count');
 for(const theme of ['light','dark']){
  await page.evaluate(theme=>document.documentElement.classList.toggle('dark',theme==='dark'),theme);
  await page.screenshot({animations:'disabled',path:evidence+'/trace-list-'+theme+'.png',fullPage:true});
  await setViewport({width:1920,height:1080});
  await page.screenshot({animations:'disabled',path:evidence+'/trace-list-'+theme+'-wide.png',fullPage:true});
  await setViewport({width:1400,height:980});
  await page.getByRole('button',{name:'All time',exact:true}).click();
  await page.screenshot({animations:'disabled',path:evidence+'/trace-time-'+theme+'.png',fullPage:true});await page.keyboard.press('Escape');
 }
 await page.evaluate(()=>document.documentElement.classList.remove('dark'));
 await setViewport({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('trace list overflowed the mobile viewport');
 await page.waitForFunction(()=>document.querySelector('.obs-filter-rail')?.open===false);
 await assertDeveloperList(page);
 await page.screenshot({animations:'disabled',path:evidence+'/trace-list-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'All time',exact:true}).click();
 const bounds=await page.getByRole('dialog',{name:'All time',exact:true}).boundingBox();
 if(!bounds||bounds.x<0||bounds.x+bounds.width>391)throw Error('date range popover clipped on mobile');
 await page.screenshot({animations:'disabled',path:evidence+'/trace-time-mobile.png',fullPage:true});await page.keyboard.press('Escape');
 await setViewport({width:1400,height:980});
 const trace=page.locator('[data-execution-id="'+facts.main+'"] a.trace-open');
 await trace.click();
 const sheet=page.getByRole('dialog',{name:'Trace details',exact:true});await sheet.waitFor();
 await page.getByRole('heading',{name:'Trace tree',exact:true}).waitFor();
 const peek=await sheet.boundingBox();
 if(!peek||Math.abs(peek.width-700)>2||await sheet.evaluate(node=>node.matches(':modal')))throw Error('trace preview did not preserve the half-width non-modal layout');
 if((await page.locator('.obs-tree-pane').boundingBox()).height<500)throw Error('desktop trace tree was constrained to mobile height');
 const rootNode=page.locator('.obs-tree .run-node').first(),toggle=rootNode.locator('[data-observation-toggle]');
 const nodeCount=await page.locator('.observation-node').count();await toggle.click();
 if(await page.locator('.observation-node:visible').count()>=nodeCount||await toggle.getAttribute('aria-expanded')!=='false')throw Error('trace branch did not collapse');
 await toggle.click();
 const treeResize=page.getByRole('separator',{name:'Resize trace tree',exact:true});
 const widthBefore=(await page.locator('.obs-tree-pane').boundingBox()).width;
 await treeResize.focus();await treeResize.press('ArrowRight');
 if(Math.abs((await page.locator('.obs-tree-pane').boundingBox()).width-widthBefore-16)>2)throw Error('keyboard tree resizing failed');
 await treeResize.press('ArrowLeft');
 const handle=await treeResize.boundingBox();await page.mouse.move(handle.x+handle.width/2,handle.y+120);await page.mouse.down();await page.mouse.move(handle.x+handle.width/2+36,handle.y+120);await page.mouse.up();
 if((await page.locator('.obs-tree-pane').boundingBox()).width<widthBefore+32)throw Error('pointer tree resizing failed');
 const moved=await treeResize.boundingBox();await page.mouse.move(moved.x+moved.width/2,moved.y+120);await page.mouse.down();await page.mouse.move(moved.x+moved.width/2-36,moved.y+120);await page.mouse.up();
 const sheetResize=page.getByRole('separator',{name:'Resize details',exact:true}),outer=await sheetResize.boundingBox();
 await page.mouse.move(outer.x+outer.width/2,outer.y+100);await page.mouse.down();await page.mouse.move(outer.x+outer.width/2-64,outer.y+100);await page.mouse.up();
 if((await sheet.boundingBox()).width<760)throw Error('outer preview resizing failed');
 const movedOuter=await sheetResize.boundingBox();await page.mouse.move(movedOuter.x+movedOuter.width/2,movedOuter.y+100);await page.mouse.down();await page.mouse.move(movedOuter.x+movedOuter.width/2+64,movedOuter.y+100);await page.mouse.up();
 const rawInput=await page.locator('pre[data-json-source=input]').textContent();
 if(!await page.locator('.obs-io-input .control-json-tree').isVisible())throw Error('structured JSON preview missing');
 const branch=page.locator('.obs-io-input .control-json-branch').first();await branch.locator(':scope > summary').click();if(await branch.evaluate(node=>node.open))throw Error('JSON branch did not fold');await branch.locator(':scope > summary').click();
 await page.getByRole('button',{name:'JSON',exact:true}).click();
 if(!await page.locator('pre[data-json-source=input]').isVisible()||await page.locator('pre[data-json-source=input]').textContent()!==rawInput)throw Error('JSON toggle changed saved evidence');
 await page.getByRole('button',{name:'Formatted',exact:true}).click();
 const tones=await page.locator('.obs-type-icon').evaluateAll(nodes=>[...new Set(nodes.map(node=>getComputedStyle(node).color))]);if(tones.length<3)throw Error('trace types lost their semantic colors');
 await page.getByRole('searchbox',{name:'Search observations',exact:true}).fill('Provider');
 if(await page.locator('.observation-node:visible').count()>=await page.locator('.observation-node').count()||!await page.locator('.obs-tree .run-node').first().isVisible())throw Error('node search lost filtering or ancestry');
 await page.getByRole('searchbox',{name:'Search observations',exact:true}).fill('');
 await page.getByRole('button',{name:'Expand details',exact:true}).click();
 if((await sheet.boundingBox()).width<1398)throw Error('trace preview did not expand');
 await page.getByRole('button',{name:'Expand details',exact:true}).click();
 const prior=page.getByRole('button',{name:'Previous trace',exact:true});
 if(await prior.isEnabled()){
  await prior.click();await page.waitForFunction(id=>document.querySelector('[data-trace-id]')?.dataset.traceId!==id,facts.main);
  await page.getByRole('button',{name:'Next trace',exact:true}).click();await page.waitForFunction(id=>document.querySelector('[data-trace-id]')?.dataset.traceId===id,facts.main);
 }
 await page.screenshot({animations:'disabled',path:evidence+'/trace-drawer-light.png',fullPage:true});
 await setViewport({width:1920,height:1080});
 await page.screenshot({animations:'disabled',path:evidence+'/trace-drawer-wide.png',fullPage:true});
 await setViewport({width:1400,height:980});
 await page.evaluate(()=>document.documentElement.classList.add('dark'));
 await page.screenshot({animations:'disabled',path:evidence+'/trace-drawer-dark.png',fullPage:true});
 await page.evaluate(()=>document.documentElement.classList.remove('dark'));
 await setViewport({width:390,height:844});
 if(await page.locator('.control-sheet').count()!==1||await page.locator('#observability-workbench').count()!==1)throw Error('trace drawer duplicated its content');
 await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
 await writeFile(evidence+'/trace-drawer-mobile.json',JSON.stringify(await page.evaluate(()=>({viewport:{width:innerWidth,height:innerHeight},headers:[...document.querySelectorAll('.control-sheet-header')].map(node=>({text:node.textContent,rect:node.getBoundingClientRect().toJSON()})),panes:[...document.querySelectorAll('.control-sheet-body,.obs-workbench,.obs-tree-pane,.obs-detail-pane')].map(node=>({className:node.className,rect:node.getBoundingClientRect().toJSON(),scrollHeight:node.scrollHeight}))})),null,2));
 await page.screenshot({animations:'disabled',path:evidence+'/trace-drawer-mobile.png'});
 await setViewport({width:1400,height:980});
 await page.locator('.obs-tree [data-observation-id="generation:'+facts.generation+'"] a').first().click();
 await page.waitForURL(target=>target.searchParams.has('obs'));
 await page.getByRole('button',{name:'Close details',exact:true}).click();
 await page.waitForURL(list);await sheet.waitFor({state:'detached'});
 await trace.and(page.locator(':focus')).waitFor();
 await page.goForward();await sheet.waitFor();
 await page.keyboard.press('Escape');await page.waitForURL(list);await sheet.waitFor({state:'detached'});
 await trace.click();await sheet.waitFor();
 await page.getByRole('link',{name:'Open full page',exact:true}).click();
 await page.getByRole('heading',{name:'Trace tree',exact:true}).waitFor();
 if(await page.locator('.control-sheet').count())throw Error('full-page trace remained in a drawer');
 await page.goto(list);
 const plain=await browser.newContext({javaScriptEnabled:false});
 try{
  await plain.addCookies(await context.cookies());const fallback=await plain.newPage();await fallback.goto(list);
  await fallback.getByRole('searchbox',{name:'Search traces',exact:true}).fill(facts.main);
  await fallback.getByRole('searchbox',{name:'Search traces',exact:true}).press('Enter');
  await fallback.waitForURL(target=>target.searchParams.get('search')===facts.main);
  if(await fallback.locator('[data-execution-id]').count()!==1)throw Error('trace search requires JavaScript');
  await fallback.locator('a.trace-open').click();await fallback.getByRole('heading',{name:'Trace tree',exact:true}).waitFor();
 }finally{await plain.close()}
}
